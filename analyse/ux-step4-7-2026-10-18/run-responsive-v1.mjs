import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const dir = import.meta.dirname;
const root = path.resolve(dir, '../..');
const sha = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const freezePath = path.join(dir, 'RESPONSIVE-HARNESS-FREEZE-v1.json');
const logPath = path.join(dir, 'responsive-v1.log');
const receiptPath = path.join(dir, 'responsive-v1-command.json');
const resultsPath = path.join(dir, 'responsive-v1-results.json');
assert(!fs.existsSync(logPath) && !fs.existsSync(receiptPath) && !fs.existsSync(resultsPath), 'Never overwrite selected test evidence');
const freeze = JSON.parse(fs.readFileSync(freezePath));
const sourcePath = path.join(dir, 'CANDIDATE-SOURCE-FREEZE-v1.json');
assert.equal(sha(sourcePath), freeze.sourceFreezeSha256);
for (const item of freeze.files) assert.equal(sha(path.join(root, item.path)), item.sha256, item.path);
const source = JSON.parse(fs.readFileSync(sourcePath));
assert.equal(source.candidate, '.vercel/ux-step4-7-20261018');
for (const item of source.appInputs) assert.equal(sha(path.join(root, source.candidate, item.path)), item.sha256, item.path);

const cwd = path.join(dir, 'responsive-v1-run');
fs.mkdirSync(cwd, { recursive: true });
for (const sub of ['ux-step4-1-2026-10-14','ux-step4-2-2026-10-15','ux-step4-3-2026-10-16','ux-step4-4-2026-10-17','ux-step4-5-2026-10-17']) fs.mkdirSync(path.join(cwd, 'analyse', sub), { recursive: true });
const args = [path.join(root, 'node_modules/@playwright/test/cli.js'), 'test', '--config', path.join(dir, 'responsive-v1.playwright.config.mjs')];
const startedAt = new Date().toISOString();
const fd = fs.openSync(logPath, 'wx');
const child = spawn(process.execPath, args, { cwd, env: { ...process.env, PLAYWRIGHT_JSON_OUTPUT_FILE: resultsPath }, stdio: ['ignore', 'pipe', 'pipe'] });
let budgetExceeded = false, spawnError = null;
const budgetMs = 900000;
const timer = setTimeout(() => { budgetExceeded = true; child.kill(); }, budgetMs);
for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => { fs.writeSync(fd, chunk); process.stdout.write(chunk); });
child.on('error', error => { spawnError = String(error); fs.writeSync(fd, spawnError + '\n'); });
child.on('close', (exitCode, signal) => {
  clearTimeout(timer);
  fs.closeSync(fd);
  let postPinsMatch = sha(sourcePath) === freeze.sourceFreezeSha256;
  for (const item of freeze.files) if (sha(path.join(root, item.path)) !== item.sha256) postPinsMatch = false;
  for (const item of source.appInputs) if (sha(path.join(root, source.candidate, item.path)) !== item.sha256) postPinsMatch = false;
  const receipt = { startedAt, endedAt: new Date().toISOString(), command: ['node', ...args], cwd, exitCode, signal, budgetExceeded, runnerBudgetMs: budgetMs, caseTimeoutMs: 45000, freezeSha256: sha(freezePath), sourceFreezeSha256: freeze.sourceFreezeSha256, runnerSha256: sha(new URL(import.meta.url)), postPinsMatch, spawnError, status: exitCode === 0 && !budgetExceeded && postPinsMatch && !spawnError ? 'PASS' : 'FAIL', executionMode: 'Scoped local Edge review; no browser/proxy/CSP weakening; real outbound denied.' };
  fs.writeFileSync(receiptPath, JSON.stringify(receipt, null, 2) + '\n', { flag: 'wx' });
  console.log(JSON.stringify(receipt));
  process.exitCode = receipt.status === 'PASS' ? 0 : 1;
});
