const supplementPath=path.join(dir,'INDEPENDENT-SHARED-NAV-DESIGN-QC-v2a.vi.md');
const record={recordedAt:new Date().toISOString(),status:'PASS_DESIGN_R1_ROOT_APP_GO_PENDING',proposalFreezeSha256:sha(freezeFile),proposalPins:freeze.pins.length,addendumFreezeSha256:sha(addendumFreezeFile),addendumPins:addendumFreeze.pins.length,sourceFreezeSha256:sha(sourceFile),accepted46App:source.appInputs.length,accepted46Harness:source.harnessAndIntake.length,approved45App:prior.appInputs.length,rootPreimagesPresent:present,rootPreimagesAbsent:absent,rootTrackedDirtyPreserved:ownEarlier.trackedDirty.length,candidate47Absent:true,report:{path:path.relative(root,reportPath).replaceAll('\\','/'),sha256:sha(reportPath)},supplement:{path:path.relative(root,supplementPath).replaceAll('\\','/'),sha256:sha(supplementPath)},noBrowserOrAppInvocation:true,planningObligationsResolvedByV2a:true,remaining:'Candidate diff and actual test controls must be reviewed before browser invocation; root implementation GO remains separate'};
