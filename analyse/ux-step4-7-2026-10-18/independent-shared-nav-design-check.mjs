import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const dir=import.meta.dirname,root=path.resolve(dir,'../..');
const sha=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const freezeFile=path.join(dir,'SHARED-NAV-PROPOSAL-v2-FREEZE.json');
assert.equal(sha(freezeFile),'1c939859bf4571f54e45d684da25eb9105d597e01f0ee9f781b74247bc0b2a64');
const freeze=json(freezeFile);
for(const p of freeze.pins) assert.equal(sha(path.resolve(root,p.path)),p.sha256,p.path);
const addendumFreezeFile=path.join(dir,'SHARED-NAV-PROPOSAL-v2a-FREEZE.json');
assert.equal(sha(addendumFreezeFile),'69a83d6673acbc7e2c2c841252671ea6218b96a79f563eab8b5dc704d0c5b995');
const addendumFreeze=json(addendumFreezeFile);
for(const p of addendumFreeze.pins)assert.equal(sha(path.resolve(root,p.path)),p.sha256,p.path);
const sourceFile=path.resolve(root,freeze.approvedBaseline.path);
assert.equal(sha(sourceFile),freeze.approvedBaseline.sha256);
const source=json(sourceFile),candidate=path.resolve(root,source.candidate);
for(const p of source.appInputs)assert.equal(sha(path.resolve(candidate,p.path)),p.sha256,p.path);
for(const p of source.harnessAndIntake)assert.equal(sha(path.resolve(root,p.path)),p.sha256,p.path);
const priorFile=path.resolve(root,source.approvedSourceManifest),prior=json(priorFile);
assert.equal(sha(priorFile),'f57b2ba99aad152ffa52192ea40725ceab0a9ba6005a347323c11a880e7301a8');
for(const p of prior.appInputs)assert.equal(sha(path.resolve(root,prior.candidate,p.path)),p.sha256,p.path);
const baseline=json(path.join(dir,'BASELINE-PINS-v2.json'));
let present=0,absent=0;
for(const p of baseline.rootPreimages){const file=path.resolve(root,p.path);assert.equal(fs.existsSync(file),p.exists,p.path);if(p.exists){assert.equal(sha(file),p.sha256,p.path);present++;}else absent++;}
assert.equal(execFileSync('git',['status','--porcelain=v1','-uno'],{cwd:root,encoding:'utf8'}),baseline.trackedDirtyStatus);
const ownEarlier=json(path.join(dir,'INDEPENDENT-INTAKE-SOURCE-CHECK.json'));
for(const p of ownEarlier.trackedDirty)assert.equal(sha(path.resolve(root,p.path)),p.sha256,p.path);
assert.equal(fs.existsSync(path.resolve(root,'.vercel/ux-step4-7-20261018')),false,'candidate created before root GO');
