#!/usr/bin/env node
// Builds the server-only import list for the existing free-course catalogue (38 video lessons, 3 course groups) from
// src/courses/freeCourses.ts. The Owner imports it into the versioned content store with the import_catalog action;
// importing never approves anything. The output stays under supabase/functions/_shared and is not imported by the client.
//   node scripts/generate-video-catalog-candidates.mjs          write the file
//   node scripts/generate-video-catalog-candidates.mjs --check  fail if the file is out of date
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "supabase/functions/_shared/videoCatalogCandidates.ts");
const { FREE_COURSES } = await import(pathToFileURL(path.join(root, "src/courses/freeCourses.ts")).href);

const items = [];
for (const course of FREE_COURSES) {
  const lessonIds = [];
  for (const lesson of course.lessons) {
    const id = `video-${course.id}-${lesson.id}`;
    lessonIds.push(id);
    items.push({
      id, kind: "video_lesson", title: lesson.title,
      payload: {
        youtubeId: lesson.youtubeId, summary: lesson.description, durationLabel: lesson.duration, orientation: lesson.orientation,
        visibility: lesson.visibility, captionsVerified: lesson.channelCaptionsVerified, captionLanguages: lesson.channelCaptionLanguages,
      },
    });
  }
  items.push({
    id: `group-${course.id}`, kind: "course_group", title: course.title,
    payload: { summary: course.description, lessonIds, ...(course.guidance ? { guidance: { reviewed: course.guidance.reviewed, benefits: course.guidance.benefits, cautions: course.guidance.cautions } } : {}) },
  });
}

const body = `// GENERATED by scripts/generate-video-catalog-candidates.mjs from src/courses/freeCourses.ts — do not edit by hand.
// Server-only import list for the versioned content store. Importing records the current catalogue as submitted versions;
// it never approves anything and never makes anything learner-visible. Do not import this module from the client bundle.
export type CatalogItem = { id: string; kind: "video_lesson" | "course_group"; title: string; payload: Record<string, unknown> };
export const videoCatalogItems: CatalogItem[] = ${JSON.stringify(items, null, 2)};
`;
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(outFile, "utf8"); } catch { /* missing */ }
  if (current.replace(/\r\n/g, "\n") !== body) { console.error("videoCatalogCandidates.ts is out of date; run node scripts/generate-video-catalog-candidates.mjs"); process.exit(1); }
  console.log(`Video catalogue candidates are up to date (${items.length} items).`);
} else {
  writeFileSync(outFile, body);
  console.log(`Wrote ${items.length} items to ${path.relative(root, outFile)}`);
}
