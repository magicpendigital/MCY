#!/usr/bin/env node
// Builds the server-only review registry for the 14 reading units in content/yoga-library.
// The output stays under supabase/functions/_shared (Edge bundle). It is never imported by the
// learner client; the Owner reads it through the authenticated owner-control-plane route.
//   node scripts/generate-reading-candidates.mjs          write the file
//   node scripts/generate-reading-candidates.mjs --check  fail if the file is out of date
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const unitsDir = path.join(root, "content/yoga-library/units");
const outFile = path.join(root, "supabase/functions/_shared/readingUnitCandidates.ts");

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
  return JSON.stringify(value);
}
const pick = (source, keys) => Object.fromEntries(keys.filter(key => source[key] !== undefined).map(key => [key, source[key]]));

const candidates = [];
for (const slug of readdirSync(unitsDir).sort()) {
  const revisions = readdirSync(path.join(unitsDir, slug)).filter(name => /^r\d+\.json$/.test(name)).sort((a, b) => Number(a.slice(1, -5)) - Number(b.slice(1, -5)));
  const file = revisions.at(-1);
  if (!file) continue;
  const unit = JSON.parse(readFileSync(path.join(unitsDir, slug, file), "utf8"));
  if (unit.learnerVisible !== false || unit.recommendationEligible !== false) throw new Error(`${slug}: unit is not marked private/ineligible`);
  const content = {
    unitId: unit.id,
    revision: unit.revision,
    locale: unit.locale,
    ...pick(unit, ["title", "intro", "audience", "prerequisites", "preparation", "stopGuidance", "learningObjectives", "readTimeNote", "productionStatus", "blockers"]),
    steps: unit.steps.map(step => pick(step, ["id", "order", "title", "body", "detail", "entry", "exit", "alternative", "stopCue", "mediaIds"])),
    media: (unit.media ?? []).map(item => pick(item, ["id", "stepId", "status", "path", "sha256", "mime", "width", "height", "alt", "caption", "disclosure"])),
  };
  const id = `reading-${slug}`;
  if (!/^[a-z0-9_-]{1,80}$/.test(id)) throw new Error(`${id}: invalid candidate id`);
  const version = createHash("sha256").update(canonical({ id, scope: "learning_reading", content })).digest("hex");
  candidates.push({ id, scope: "learning_reading", version, title: String(unit.title).slice(0, 200), unit: content });
}

const source = `// GENERATED by scripts/generate-reading-candidates.mjs from content/yoga-library/units — do not edit by hand.
// Server-only review candidates: reading units are private drafts, never learner-visible and never
// eligible for AI selection. Do not import this module from the client bundle.
export type ReadingUnitStep = { id: string; order: number; title: string; body: string; detail?: string; entry?: string; exit?: string; alternative?: string; stopCue?: string; mediaIds?: string[] };
export type ReadingUnitMedia = { id: string; stepId: string; status: string; path?: string | null; sha256?: string | null; mime?: string | null; width?: number | null; height?: number | null; alt?: string | null; caption?: string | null; disclosure?: string | null };
export type ReadingUnitContent = {
  unitId: string; revision: string; locale: string; title: string; intro?: string; audience?: string;
  prerequisites?: unknown; preparation?: unknown; stopGuidance?: unknown; learningObjectives?: unknown; readTimeNote?: string;
  productionStatus?: string; blockers?: unknown; steps: ReadingUnitStep[]; media: ReadingUnitMedia[];
};
export type ReadingUnitCandidate = { id: string; scope: "learning_reading"; version: string; title: string; unit: ReadingUnitContent };

export const readingUnitCandidates: readonly ReadingUnitCandidate[] = ${JSON.stringify(candidates, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n"); } catch {}
  if (current !== source) { console.error("readingUnitCandidates.ts is out of date. Run: node scripts/generate-reading-candidates.mjs"); process.exit(1); }
  console.log(`Reading candidates up to date (${candidates.length} units).`);
} else {
  writeFileSync(outFile, source);
  console.log(`Wrote ${path.relative(root, outFile)} with ${candidates.length} candidates (${Math.round(source.length / 1024)} KB).`);
}
